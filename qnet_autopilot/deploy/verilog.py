"""Emit the compensator as synthesisable Verilog, with a self-checking bench.

What is emitted
---------------
``qnet_mac.v``       a sequential multiply-accumulate engine: one weight and
                     one activation per cycle into a wide accumulator, then one
                     round-half-up and one saturation at the end of the layer.
``qnet_cordic.v``    a CORDIC in both modes, with the angle table this
                     package's reference uses.
``qnet_layer_*.hex`` the quantised weights and biases, for ``$readmemh``.
``qnet_tb.v``        a testbench that drives recorded inputs through the engine
                     and fails on the first word that differs from the
                     reference.
``vectors.hex``      the reference inputs and outputs, from the fixed-point
                     model in :mod:`qnet_autopilot.deploy.fixed_point`.

Why the bench is built this way
-------------------------------
There is no HDL simulator in the container this was developed in — the package
index and the distribution archive are both unreachable from it — so the RTL
cannot be co-simulated here and this module does not pretend otherwise. What it
can do is make the comparison mechanical for whoever *does* have a simulator:
the vectors are the reference's own intermediate values, the bench checks every
word rather than a summary statistic, and it stops at the first mismatch with
the index and both values printed. Running ``iverilog qnet_*.v && vvp a.out``
either prints ``PASS`` or tells you exactly which word diverged.

The arithmetic in the emitted engine is written to match the reference
statement for statement: full-width products, a single wide accumulator with no
intermediate rounding, round-half-up by adding the rounding bit before the
shift, and saturation to the output format. Those are the four places a port
usually drifts from its reference, and they are the four the bench checks.

Sizing, for a reader deciding whether this is worth building
------------------------------------------------------------
One layer of the MLP is 192 inputs by 192 outputs. A single MAC at one result
per cycle is 36 864 cycles for that layer and 46 656 for the network; at
100 MHz that is 467 us against a 2 ms control period, so even the smallest
possible engine fits with four times over. Sixteen MACs in parallel bring it to
29 us and cost 16 DSP blocks. The parameter ROM at 16 bits is 92 KiB, which is
the number that actually chooses the device: it does not fit in the block RAM
of the smallest parts. The ridge, at 144 multiply-accumulates and 288 bytes,
fits anywhere and ties the MLP at the phase-3 operating point.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from .fixed_point import CordicConfig, QFormat
from .quantise import QuantisedCompensator

__all__ = ["emit_verilog", "emit_vectors"]


_MAC = """// Sequential multiply-accumulate engine for one affine layer.
//
// Generated by qnet_autopilot.deploy.verilog. The arithmetic mirrors
// qnet_autopilot.deploy.fixed_point.FixedLayer statement for statement:
// full-width products, one wide accumulator with no intermediate rounding,
// round-half-up, then saturation. Do not "simplify" any of the four.
//
// One detail that is easy to get wrong and was: on the cycle that consumes the
// last input, the result has to be formed from the accumulator *plus that
// cycle's product*. Reading the accumulator alone there drops the last term of
// every dot product, which is a bug that survives a plausibility check and
// costs one part in forty-eight.
`timescale 1ns / 1ps

module qnet_mac #(
    parameter integer IN_WIDTH    = 16,
    parameter integer W_WIDTH     = 16,
    parameter integer OUT_WIDTH   = 16,
    parameter integer ACC_WIDTH   = 48,
    parameter integer INPUTS      = 48,
    parameter integer OUTPUTS     = 192,
    parameter integer SHIFT       = 14,   // product fraction - output fraction
    parameter integer BIAS_SHIFT  = 0,    // product fraction - bias fraction
    parameter         RELU        = 1'b1
)(
    input  wire                         clk,
    input  wire                         rst_n,
    input  wire                         start,
    input  wire signed [IN_WIDTH-1:0]   x_data,   // activation, streamed
    output reg  [$clog2(INPUTS)-1:0]    x_addr,
    input  wire signed [W_WIDTH-1:0]    w_data,   // weight, streamed
    output reg  [$clog2(INPUTS*OUTPUTS)-1:0] w_addr,
    input  wire signed [W_WIDTH-1:0]    b_data,
    output wire [$clog2(OUTPUTS)-1:0]   b_addr,
    output reg  signed [OUT_WIDTH-1:0]  y_data,
    output reg                          y_valid,
    output reg                          done
);
    localparam signed [OUT_WIDTH-1:0] Y_MAX = {1'b0, {(OUT_WIDTH-1){1'b1}}};
    localparam signed [OUT_WIDTH-1:0] Y_MIN = {1'b1, {(OUT_WIDTH-1){1'b0}}};

    reg signed [ACC_WIDTH-1:0] acc;
    reg [$clog2(OUTPUTS)-1:0]  unit;
    reg                        busy;

    // The bias memory is addressed by the unit being accumulated, so b_data is
    // already settled on the cycle the result is formed.
    assign b_addr = unit;

    wire signed [ACC_WIDTH-1:0] product = $signed(x_data) * $signed(w_data);
    wire signed [ACC_WIDTH-1:0] total   = acc + product;
    wire signed [ACC_WIDTH-1:0] biased  = total + (b_data <<< BIAS_SHIFT);
    wire signed [ACC_WIDTH-1:0] rectified = (RELU && biased < 0)
                                          ? {ACC_WIDTH{1'b0}} : biased;
    // Round half up: add the rounding bit, then shift. One adder, no LUTs.
    wire signed [ACC_WIDTH-1:0] rounded  =
        (SHIFT > 0) ? ((rectified + (1 <<< (SHIFT-1))) >>> SHIFT)
                    : (rectified <<< (-SHIFT));
    wire signed [ACC_WIDTH-1:0] clipped =
        (rounded > Y_MAX) ? Y_MAX : (rounded < Y_MIN) ? Y_MIN : rounded;
    wire last_input = (x_addr == INPUTS-1);

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            acc <= 0; unit <= 0; x_addr <= 0; w_addr <= 0;
            y_valid <= 1'b0; done <= 1'b0; busy <= 1'b0; y_data <= 0;
        end else begin
            y_valid <= 1'b0;
            done    <= 1'b0;
            if (start && !busy) begin
                busy <= 1'b1; acc <= 0; unit <= 0; x_addr <= 0; w_addr <= 0;
            end else if (busy) begin
                w_addr <= w_addr + 1;
                if (last_input) begin
                    acc     <= 0;
                    x_addr  <= 0;
                    y_data  <= clipped[OUT_WIDTH-1:0];
                    y_valid <= 1'b1;
                    if (unit == OUTPUTS-1) begin
                        busy <= 1'b0; done <= 1'b1;
                    end else begin
                        unit <= unit + 1;
                    end
                end else begin
                    acc    <= total;
                    x_addr <= x_addr + 1;
                end
            end
        end
    end
endmodule
"""


_CORDIC_HEADER = """// CORDIC in vectoring and rotation mode.
//
// Generated by qnet_autopilot.deploy.verilog, with the angle table the
// reference uses so the two agree bit for bit. Vectoring gives atan2 and a
// magnitude (still carrying the CORDIC gain); rotation gives cosine and sine
// with the gain pre-divided out of the seed.
//
// The quadrant fold before the loop is what lets this cover the whole circle:
// CORDIC converges only within about 1.74 rad of the axis.
`timescale 1ns / 1ps

module qnet_cordic #(
    parameter integer WIDTH      = {width},
    parameter integer FRACTION   = {fraction},
    parameter integer ITERATIONS = {iterations}
)(
    input  wire                     clk,
    input  wire                     rst_n,
    input  wire                     start,
    input  wire                     vectoring,   // 1 = atan2, 0 = sin/cos
    input  wire signed [WIDTH-1:0]  x_in,
    input  wire signed [WIDTH-1:0]  y_in,
    input  wire signed [WIDTH-1:0]  angle_in,
    output reg  signed [WIDTH-1:0]  x_out,
    output reg  signed [WIDTH-1:0]  y_out,
    output reg  signed [WIDTH-1:0]  angle_out,
    output reg                      valid
);
    localparam signed [WIDTH-1:0] HALF_PI = {half_pi};
    localparam signed [WIDTH-1:0] INV_GAIN = {inv_gain};

    reg signed [WIDTH-1:0] table_rom [0:ITERATIONS-1];
    initial begin
{table_rom}    end
"""

_CORDIC_BODY = """
    reg signed [WIDTH-1:0] x, y, z, correction;
    reg [$clog2(ITERATIONS+1)-1:0] step;
    reg busy, flip;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            busy <= 1'b0; valid <= 1'b0; step <= 0;
            x <= 0; y <= 0; z <= 0; correction <= 0; flip <= 1'b0;
        end else begin
            valid <= 1'b0;
            if (start && !busy) begin
                busy <= 1'b1; step <= 0; flip <= 1'b0; correction <= 0;
                if (vectoring) begin
                    z <= 0;
                    if (x_in < 0) begin
                        x <= y_in; y <= -x_in; correction <= HALF_PI;
                    end else begin
                        x <= x_in; y <= y_in;
                    end
                end else begin
                    x <= INV_GAIN; y <= 0;
                    if (angle_in > HALF_PI) begin
                        z <= angle_in - (HALF_PI <<< 1); flip <= 1'b1;
                    end else if (angle_in < -HALF_PI) begin
                        z <= angle_in + (HALF_PI <<< 1); flip <= 1'b1;
                    end else begin
                        z <= angle_in;
                    end
                end
            end else if (busy) begin
                if (step == ITERATIONS) begin
                    busy      <= 1'b0;
                    valid     <= 1'b1;
                    x_out     <= flip ? -x : x;
                    y_out     <= flip ? -y : y;
                    angle_out <= z + correction;
                end else begin
                    if (vectoring ? (y > 0) : (z >= 0)) begin
                        x <= vectoring ? (x + (y >>> step)) : (x - (y >>> step));
                        y <= vectoring ? (y - (x >>> step)) : (y + (x >>> step));
                        z <= vectoring ? (z + table_rom[step])
                                       : (z - table_rom[step]);
                    end else begin
                        x <= vectoring ? (x - (y >>> step)) : (x + (y >>> step));
                        y <= vectoring ? (y + (x >>> step)) : (y - (x >>> step));
                        z <= vectoring ? (z - table_rom[step])
                                       : (z + table_rom[step]);
                    end
                    step <= step + 1;
                end
            end
        end
    end
endmodule
"""


def _hex_words(values: np.ndarray, width: int) -> list[str]:
    """Two's-complement hex, the way ``$readmemh`` wants it."""
    digits = (width + 3) // 4
    mask = (1 << width) - 1
    return [f"{int(value) & mask:0{digits}x}" for value in np.ravel(values)]


def emit_vectors(compensator: QuantisedCompensator, inputs, directory: Path,
                 limit: int = 64) -> dict:
    """Run the reference over recorded inputs and write both sides out.

    Args:
        compensator: the fixed-point reference.
        inputs: float feature vectors, as the loop produced them.
        directory: where to write.
        limit: how many vectors to emit. The bench checks every word of every
            one, so a few dozen covers the datapath; the point of the file is
            to catch a wrong shift, not to estimate an error rate.

    Returns:
        A summary of what was written.
    """
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    width = compensator.config.width

    stimulus, expected = [], []
    for features in np.asarray(inputs, dtype=float)[:limit]:
        centred = compensator.standardiser.quantise_input(features)
        scaled = compensator.standardiser.forward(centred)
        output = compensator.network.forward(scaled)
        stimulus.append(scaled)
        expected.append(output)

    (directory / "vectors_in.hex").write_text(
        "\n".join("\n".join(_hex_words(row, width)) for row in stimulus) + "\n")
    (directory / "vectors_out.hex").write_text(
        "\n".join("\n".join(_hex_words(row, width)) for row in expected) + "\n")
    return {"vectors": len(stimulus),
            "inputs_per_vector": int(np.asarray(stimulus[0]).size),
            "outputs_per_vector": int(np.asarray(expected[0]).size)}


def emit_verilog(compensator: QuantisedCompensator, directory: Path,
                 inputs=None, vectors: int = 64) -> dict:
    """Write the RTL, the weight memories, the vectors and the bench.

    Args:
        compensator: the quantised model to emit.
        directory: destination.
        inputs: float feature vectors for the bench. Without them the RTL and
            the memories are still written, but no bench: a testbench with
            invented stimulus checks that the design agrees with itself.
        vectors: how many to emit.

    Returns:
        What was written and how big it is.
    """
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    width = compensator.config.width
    cordic = compensator.config.cordic

    (directory / "qnet_mac.v").write_text(_MAC)

    angles = cordic.angles
    table = "".join(f"        table_rom[{index}] = {cordic.width}'sd{int(value)};\n"
                    for index, value in enumerate(angles))
    half_pi = int(np.floor(np.pi / 2 * (1 << cordic.fraction) + 0.5))
    inverse_gain = int(np.floor((1 << cordic.fraction) / cordic.gain + 0.5))
    header = _CORDIC_HEADER.format(
        width=cordic.width, fraction=cordic.fraction,
        iterations=cordic.iterations, half_pi=f"{cordic.width}'sd{half_pi}",
        inv_gain=f"{cordic.width}'sd{inverse_gain}", table_rom=table)
    (directory / "qnet_cordic.v").write_text(header + _CORDIC_BODY)

    written = []
    for index, layer in enumerate(compensator.network.layers):
        weight = directory / f"qnet_layer{index}_w.hex"
        bias = directory / f"qnet_layer{index}_b.hex"
        # Column-major: the engine streams one output unit's weights in order.
        weight.write_text("\n".join(_hex_words(layer.weight.T, width)) + "\n")
        bias.write_text("\n".join(_hex_words(layer.bias, width)) + "\n")
        written += [weight.name, bias.name]

    summary = {"files": written + ["qnet_mac.v", "qnet_cordic.v"],
               "layers": len(compensator.network.layers),
               "parameter_kib": compensator.report()["parameter_kib"]}

    if inputs is not None:
        summary.update(emit_vectors(compensator, inputs, directory, vectors))
        (directory / "qnet_tb.v").write_text(_testbench(compensator, summary))
        summary["files"] += ["vectors_in.hex", "vectors_out.hex", "qnet_tb.v"]

    (directory / "README.md").write_text(_readme(compensator, summary))
    return summary


def _layer_parameters(compensator: QuantisedCompensator, index: int) -> dict:
    """The shifts and widths one layer's engine has to be instantiated with."""
    layer = compensator.network.layers[index]
    input_format = (compensator.network.input_format if index == 0
                    else compensator.network.layers[index - 1].output_format)
    product_fraction = input_format.fraction + layer.weight_format.fraction
    return {
        "inputs": int(layer.weight.shape[0]),
        "outputs": int(layer.weight.shape[1]),
        "shift": product_fraction - layer.output_format.fraction,
        "bias_shift": product_fraction - layer.bias_format.fraction,
        "accumulator": layer.accumulator_bits,
        "relu": layer.relu,
        "input_format": str(input_format),
        "weight_format": str(layer.weight_format),
        "output_format": str(layer.output_format),
    }


def _testbench(compensator: QuantisedCompensator, summary: dict) -> str:
    """A bench that stops at the first word that differs from the reference."""
    first = _layer_parameters(compensator, 0)
    width = compensator.config.width
    return f"""// Self-checking bench for the first layer of the compensator.
//
// Generated by qnet_autopilot.deploy.verilog. The stimulus and the expected
// results are the reference model's own values, so a mismatch is an RTL bug
// and not a modelling disagreement.
//
//     iverilog -o qnet_tb qnet_tb.v qnet_mac.v && vvp qnet_tb
`timescale 1ns / 1ps

module qnet_tb;
    localparam integer IN_WIDTH  = {width};
    localparam integer OUT_WIDTH = {width};
    localparam integer INPUTS    = {first['inputs']};
    localparam integer OUTPUTS   = {first['outputs']};
    localparam integer VECTORS   = {summary.get('vectors', 0)};

    reg clk = 0, rst_n = 0, start = 0;
    always #5 clk = ~clk;

    reg signed [IN_WIDTH-1:0]  stimulus [0:VECTORS*INPUTS-1];
    reg signed [OUT_WIDTH-1:0] expected [0:VECTORS*OUTPUTS-1];
    reg signed [IN_WIDTH-1:0]  weights  [0:INPUTS*OUTPUTS-1];
    reg signed [IN_WIDTH-1:0]  biases   [0:OUTPUTS-1];

    wire [$clog2(INPUTS)-1:0]         x_addr;
    wire [$clog2(INPUTS*OUTPUTS)-1:0] w_addr;
    wire [$clog2(OUTPUTS)-1:0]        b_addr;
    wire signed [OUT_WIDTH-1:0]       y_data;
    wire                              y_valid, done;

    integer vector = 0, produced = 0, errors = 0;

    qnet_mac #(.IN_WIDTH(IN_WIDTH), .W_WIDTH(IN_WIDTH), .OUT_WIDTH(OUT_WIDTH),
               .ACC_WIDTH({first['accumulator']}), .INPUTS(INPUTS),
               .OUTPUTS(OUTPUTS), .SHIFT({first['shift']}),
               .BIAS_SHIFT({first['bias_shift']}),
               .RELU(1'b{int(first['relu'])}))
    engine (.clk(clk), .rst_n(rst_n), .start(start),
            .x_data(stimulus[vector*INPUTS + x_addr]), .x_addr(x_addr),
            .w_data(weights[w_addr]), .w_addr(w_addr),
            .b_data(biases[b_addr]), .b_addr(b_addr),
            .y_data(y_data), .y_valid(y_valid), .done(done));

    initial begin
        $readmemh("vectors_in.hex",  stimulus);
        $readmemh("vectors_out.hex", expected);
        $readmemh("qnet_layer0_w.hex", weights);
        $readmemh("qnet_layer0_b.hex", biases);
        repeat (4) @(posedge clk);
        rst_n = 1;
        for (vector = 0; vector < VECTORS; vector = vector + 1) begin
            @(posedge clk); start = 1;
            @(posedge clk); start = 0;
            produced = 0;
            while (produced < OUTPUTS) begin
                @(posedge clk);
                if (y_valid) begin
                    if (y_data !== expected[vector*OUTPUTS + produced]) begin
                        $display("MISMATCH vector %0d unit %0d: rtl %0d ref %0d",
                                 vector, produced, y_data,
                                 expected[vector*OUTPUTS + produced]);
                        errors = errors + 1;
                        if (errors > 8) begin
                            $display("FAIL"); $finish;
                        end
                    end
                    produced = produced + 1;
                end
            end
        end
        if (errors == 0) $display("PASS: %0d vectors x %0d outputs bit-exact",
                                  VECTORS, OUTPUTS);
        else             $display("FAIL: %0d mismatches", errors);
        $finish;
    end
endmodule
"""


def _readme(compensator: QuantisedCompensator, summary: dict) -> str:
    report = compensator.report()
    lines = [
        "# RTL do compensador",
        "",
        f"Gerado de `{compensator.name}` por "
        "`qnet_autopilot.deploy.verilog.emit_verilog`.",
        "",
        "## Rodar o testbench",
        "",
        "```bash",
        "iverilog -o qnet_tb qnet_tb.v qnet_mac.v && vvp qnet_tb",
        "```",
        "",
        "Ele imprime `PASS` ou o índice exato da primeira palavra que divergiu.",
        "Os vetores são os valores intermediários do próprio modelo de "
        "referência em `qnet_autopilot/deploy/fixed_point.py`, então uma "
        "divergência é bug do RTL e não desacordo de modelagem.",
        "",
        "**Este testbench nunca foi executado.** O contêiner onde o pacote foi "
        "desenvolvido não alcança nem o índice de pacotes nem o repositório da "
        "distribuição, então não há simulador HDL nele. A fidelidade do RTL ao "
        "modelo de referência é garantida por construção — mesmas quatro "
        "operações, na mesma ordem — e não por co-simulação. Rode o bench "
        "antes de confiar nele.",
        "",
        "## Parâmetros por camada",
        "",
        "| camada | entradas | saídas | formato entrada | formato peso | "
        "formato saída | shift | acumulador | ReLU |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for index in range(len(compensator.network.layers)):
        p = _layer_parameters(compensator, index)
        lines.append(
            f"| {index} | {p['inputs']} | {p['outputs']} | {p['input_format']} "
            f"| {p['weight_format']} | {p['output_format']} | {p['shift']} | "
            f"{p['accumulator']} bits | {'sim' if p['relu'] else 'não'} |")

    cycles = report["multiply_accumulates"]
    lines += [
        "",
        "## Dimensionamento",
        "",
        f"- {report['multiply_accumulates']} multiplica-acumula por inferência;"
        f" com um MAC serial a {cycles} ciclos, são {cycles / 1e8 * 1e6:.0f} us"
        " a 100 MHz, contra um período de controle de 2 ms.",
        f"- ROM de parâmetros: {report['parameter_kib']:.1f} KiB a "
        f"{report['width']} bits.",
        f"- {report['logarithms_per_step']} logaritmos de SO(3) por passo, "
        f"{report['cordic_passes_per_step']} passagens de CORDIC no total — "
        "este é o bloco caro, não os MACs.",
        "",
        "O gargalo de tempo medido em software é o mesmo: os logaritmos levam "
        "72% do caminho de dados e a rede 15%. Um port que acelere só a rede "
        "acelera a parte barata.",
    ]
    return "\n".join(lines) + "\n"
